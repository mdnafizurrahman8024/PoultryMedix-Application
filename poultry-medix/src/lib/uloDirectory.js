export function requestTelemedicineReferral({ concern = '', district = '' } = {}) {
  if (typeof window === 'undefined') return
  const payload = {
    concern: String(concern || '').trim(),
    district: String(district || '').trim(),
    timestamp: Date.now(),
  }
  try {
    sessionStorage.setItem(POULTRYMEDIX_TELEMEDICINE_PREFILL_KEY, JSON.stringify(payload))
  } catch {
    // Ignore storage restriction
  }
  window.dispatchEvent(new CustomEvent(POULTRYMEDIX_OPEN_TELEMEDICINE_EVENT, { detail: payload }))
}

export function consumeTelemedicinePrefill() {
  if (typeof window === 'undefined') return null
  try {
    const raw = sessionStorage.getItem(POULTRYMEDIX_TELEMEDICINE_PREFILL_KEY)
    if (!raw) return null
    sessionStorage.removeItem(POULTRYMEDIX_TELEMEDICINE_PREFILL_KEY)
    const parsed = JSON.parse(raw)
    return parsed && typeof parsed === 'object' ? parsed : null
  } catch {
    return null
  }
}

export function requestUloDirectoryModal({ district = '' } = {}) {
  if (typeof window === 'undefined') return
  window.dispatchEvent(
    new CustomEvent(POULTRYMEDIX_OPEN_ULO_EVENT, {
      detail: { district: String(district || '').trim() },
    })
  )
}

