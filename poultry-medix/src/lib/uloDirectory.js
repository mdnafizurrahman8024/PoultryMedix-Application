export const POULTRYMEDIX_OPEN_TELEMEDICINE_EVENT = 'poultrymedix-open-telemedicine'
export const POULTRYMEDIX_OPEN_ULO_EVENT = 'poultrymedix-open-ulo'
export const POULTRYMEDIX_TELEMEDICINE_PREFILL_KEY = 'poultrymedix_telemedicine_prefill'

export const DLS_EMERGENCY_HELPLINE = '16358'
